/* System Chart — interface to the RT14 procedural system generator.
   Structure mirrors reach_map_tool/app.js: vanilla JS + SVG, file:// safe,
   data via data.js / options.js wrappers regenerated by gen_system.py.
   Deep-link contract for the sector tool: index.html#<system_id>            */
'use strict';

const LIB = window.SYSTEM_LIBRARY || { systems: [] };
const OPT = window.SYSTEM_OPTIONS || {};

/* ---------- constants ---------- */
const W = 2000, H = 2000, CX = 1000, CY = 1000;
const ZONES = ['inner_cauldron', 'primary_biosphere', 'outer_reaches'];
const ZONE_LABEL = { inner_cauldron: 'INNER CAULDRON', primary_biosphere: 'PRIMARY BIOSPHERE', outer_reaches: 'OUTER REACHES' };
const ZONE_BAND = { inner_cauldron: [170, 420], primary_biosphere: [420, 690], outer_reaches: [690, 950] };
const ZONE_TINT = { inner_cauldron: '#8a4a2a', primary_biosphere: '#5a7a4a', outer_reaches: '#3a4a6a' };
const STAR_COLOR = { 'Mighty': '#f0c845', 'Vigorous': '#f3ead2', 'Luminous': '#e8a13c', 'Dull': '#c46a3f', 'Anomalous': '#9a7ab8', 'Binary': '#f3ead2' };
const PLANET_R = { 'Low-Mass': 8, 'Small': 9, 'Small and Dense': 9, 'Large': 13, 'Large and Dense': 13, 'Vast': 17 };
const GAS_R = { 'Gas Dwarf': 15, 'Gas Giant': 19, 'Massive Gas Giant': 23 };
const CLIMATE_FILL = { 'Burning World': '#c4623a', 'Hot World': '#c98a4b', 'Temperate World': '#7da06b', 'Cold World': '#9fb3c0', 'Ice World': '#dde6ea' };
const INK = '#2e2218';

/* ---------- state ---------- */
let S = null;                 // current system (live object inside LIB)
let sel = null;               // {kind:'star'} | {kind:'el', zone, idx}
let undoStacks = {};          // system id -> [json,...]
let dirty = false;
let view = { x: 0, y: 0, k: 0.42 };
let drag = null;

const $ = id => document.getElementById(id);
const deep = o => JSON.parse(JSON.stringify(o));
const esc = s => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

function roman(n) {
  const T = [[1000,'M'],[900,'CM'],[500,'D'],[400,'CD'],[100,'C'],[90,'XC'],[50,'L'],[40,'XL'],[10,'X'],[9,'IX'],[5,'V'],[4,'IV'],[1,'I']];
  let r = ''; for (const [v, s] of T) while (n >= v) { r += s; n -= v; } return r;
}

/* ---------- geometry ---------- */
function zoneElements(z) { return (S.solar_zones[z] && S.solar_zones[z].elements) || []; }
function realEls(z) { return zoneElements(z).map((e, i) => ({ e, i })).filter(x => x.e.element_type !== 'No Feature'); }
function orbitR(zone, slot, count) {
  const [r0, r1] = ZONE_BAND[zone];
  return count ? r0 + (slot + 0.5) * (r1 - r0) / count : (r0 + r1) / 2;
}
function elPos(zone, idx) {
  const reals = realEls(zone);
  const slot = reals.findIndex(x => x.i === idx);
  const r = orbitR(zone, slot, reals.length);
  const el = zoneElements(zone)[idx];
  const a = ((el._ui && el._ui.angle) || 0) * Math.PI / 180;
  return { x: CX + r * Math.cos(a), y: CY + r * Math.sin(a), r };
}

/* ---------- defaults / naming ---------- */
function ensureDefaults(sys) {
  let seq = 1, gold = -80;
  for (const z of ZONES) {
    if (!sys.solar_zones[z]) sys.solar_zones[z] = { elements: [] };
    const els = sys.solar_zones[z].elements || (sys.solar_zones[z].elements = []);
    for (const el of els) {
      if (el.element_type === 'No Feature') continue;
      if (!el._ui) { el._ui = { angle: ((gold += 137.5) % 360) }; }
      if ((el.element_type === 'Planet' || el.element_type === 'Gas Giant')) {
        if (!el.name) el.name = sys.name + ' ' + roman(seq);
        seq++;
        if (!el.details) el.details = {};
      }
    }
  }
}

/* ---------- glyphs (all original ink-style drawings) ---------- */
function moonDecor(el, R) {
  const feats = (el.details && el.details.orbital_features) || [];
  let svg = '', moons = 0, rings = 0, rocks = 0;
  for (const f of feats) {
    const n = typeof f === 'string' ? f : (f.name || '');
    if (/Lesser Moon|^Moon/i.test(n)) moons++;
    else if (/Rings/i.test(n)) rings++;
    else if (/Large Asteroid/i.test(n)) rocks++;
  }
  if (rings) svg += `<ellipse rx="${R + 11}" ry="${(R + 11) * .32}" fill="none" stroke="${INK}" stroke-width="1.6" stroke-dasharray="${rings > 1 ? '1 3' : ''}" opacity=".8" transform="rotate(-18)"/>`;
  const sats = moons + rocks;
  if (sats) {
    const mr = R + 17;
    svg += `<circle r="${mr}" class="orbit" style="stroke-dasharray:2 4;stroke-opacity:.5"/>`;
    for (let i = 0; i < sats; i++) {
      const a = -Math.PI / 2 + i * (2 * Math.PI / Math.max(sats, 3));
      const sz = i < moons ? 3.2 : 1.8;
      svg += `<circle cx="${(mr * Math.cos(a)).toFixed(1)}" cy="${(mr * Math.sin(a)).toFixed(1)}" r="${sz}" fill="${INK}"/>`;
    }
  }
  return svg;
}
function elementGlyph(el) {
  const t = el.element_type, d = el.details || {};
  if (t === 'Planet') {
    const R = PLANET_R[d.body_size] || PLANET_R[d.body_class] || 10;
    const fill = CLIMATE_FILL[d.climate] || '#b8a98c';
    return { R, svg: `<circle r="${R}" fill="${fill}" stroke="${INK}" stroke-width="1.8"/>` +
      `<path d="M ${-R} 0 A ${R} ${R} 0 0 0 ${R} 0 Z" fill="${INK}" opacity=".14"/>` + moonDecor(el, R) };
  }
  if (t === 'Gas Giant') {
    const R = GAS_R[d.body_class] || GAS_R[d.body_size] || 19;
    let stripes = '';
    for (const fy of [-0.45, -0.05, 0.4]) {
      const y = R * fy, hw = Math.sqrt(R * R - y * y) * 0.96;
      stripes += `<line x1="${-hw}" y1="${y}" x2="${hw}" y2="${y}" stroke="${INK}" stroke-width="2.2" opacity=".25"/>`;
    }
    return { R, svg: `<circle r="${R}" fill="#c9a05a" stroke="${INK}" stroke-width="1.8"/>${stripes}` + moonDecor(el, R) };
  }
  if (t === 'Asteroid Belt') {
    let dots = '';
    for (let i = 0; i < 7; i++) { const a = i * 0.9, rr = 10 + (i % 3) * 4; dots += `<circle cx="${(rr * Math.cos(a)).toFixed(1)}" cy="${(rr * Math.sin(a) * .4).toFixed(1)}" r="${1.4 + (i % 2)}" fill="${INK}"/>`; }
    return { R: 16, belt: true, svg: dots };
  }
  if (t === 'Asteroid Cluster') {
    let dots = '';
    for (let i = 0; i < 5; i++) { const a = 1.1 * i, rr = 4 + i * 2.4; dots += `<circle cx="${(rr * Math.cos(a)).toFixed(1)}" cy="${(rr * Math.sin(a)).toFixed(1)}" r="${1.6 + (i % 2)}" fill="${INK}"/>`; }
    return { R: 14, svg: dots };
  }
  if (t === 'Dust Cloud') {
    let stip = '';
    for (let i = 0; i < 14; i++) { const a = i * 2.39996, rr = 3 + 16 * Math.sqrt((i + .5) / 14); stip += `<circle cx="${(rr * Math.cos(a)).toFixed(1)}" cy="${(rr * Math.sin(a)).toFixed(1)}" r=".9" fill="${INK}" opacity=".6"/>`; }
    return { R: 20, svg: `<circle r="19" fill="${INK}" opacity=".06" stroke="${INK}" stroke-width="1" stroke-dasharray="1 4"/>` + stip };
  }
  if (t === 'Gravity Riptide') {
    return { R: 16, svg: ['', 120, 240].map((rot, i) =>
      `<path d="M 0 -14 A 14 14 0 0 1 12 7" fill="none" stroke="${INK}" stroke-width="2" transform="rotate(${rot || 0}) scale(${1 - i * .28})"/>`).join('') +
      `<circle r="2.4" fill="${INK}"/>` };
  }
  if (/Radiation|Solar Flare/i.test(t)) {
    let rays = '';
    for (let i = 0; i < 8; i++) { const a = i * Math.PI / 4; rays += `<line x1="${(6 * Math.cos(a)).toFixed(1)}" y1="${(6 * Math.sin(a)).toFixed(1)}" x2="${(15 * Math.cos(a)).toFixed(1)}" y2="${(15 * Math.sin(a)).toFixed(1)}" stroke="${INK}" stroke-width="1.8"/>`; }
    return { R: 15, svg: `<circle r="5" fill="#c4623a" stroke="${INK}" stroke-width="1.5"/>${rays}` };
  }
  if (t === 'Derelict Station') {
    return { R: 14, svg: `<rect x="-8" y="-8" width="16" height="16" fill="none" stroke="${INK}" stroke-width="2" transform="rotate(45)"/>` +
      `<line x1="0" y1="-13" x2="0" y2="13" stroke="${INK}" stroke-width="1.4"/><circle r="3" fill="${INK}"/>` };
  }
  if (t === 'Starship Graveyard') {
    return { R: 15, svg: `<g stroke="${INK}" stroke-width="2.4" stroke-linecap="round">` +
      `<line x1="-11" y1="-9" x2="9" y2="11"/><line x1="9" y1="-11" x2="-9" y2="9"/>` +
      `<line x1="-11" y1="-9" x2="-5" y2="-12"/><line x1="9" y1="11" x2="13" y2="7"/></g>` };
  }
  return { R: 12, svg: `<path d="M 0 -10 L 10 0 L 0 10 L -10 0 Z" fill="none" stroke="${INK}" stroke-width="2"/>` };
}
function starGlyph(star) {
  const t = (star && star.type) || 'Vigorous';
  const c = STAR_COLOR[t] || '#f3ead2';
  let rays = '';
  for (let i = 0; i < 16; i++) {
    const a = i * Math.PI / 8, L = i % 2 ? 96 : 116;
    rays += `<line x1="${(74 * Math.cos(a)).toFixed(1)}" y1="${(74 * Math.sin(a)).toFixed(1)}" x2="${(L * Math.cos(a)).toFixed(1)}" y2="${(L * Math.sin(a)).toFixed(1)}" stroke="${INK}" stroke-width="2" opacity=".55"/>`;
  }
  let core = t === 'Binary'
    ? `<circle cx="-26" cy="0" r="44" fill="${c}" stroke="${INK}" stroke-width="2.5"/><circle cx="34" cy="8" r="28" fill="#e8a13c" stroke="${INK}" stroke-width="2.5"/>`
    : `<circle r="66" fill="${c}" stroke="${INK}" stroke-width="2.5"/>`;
  return `${rays}${core}<circle class="halo" r="126"/>`;
}

/* ---------- render ---------- */
function annulus(r0, r1, fill, op) {
  return `<path class="zone-band" fill="${fill}" fill-opacity="${op}" fill-rule="evenodd" d="M ${CX - r1} ${CY} a ${r1} ${r1} 0 1 0 ${2 * r1} 0 a ${r1} ${r1} 0 1 0 ${-2 * r1} 0 M ${CX - r0} ${CY} a ${r0} ${r0} 0 1 0 ${2 * r0} 0 a ${r0} ${r0} 0 1 0 ${-2 * r0} 0 Z"/>`;
}
function render() {
  const world = $('world');
  if (!S) { world.innerHTML = '<div style="padding:2rem;color:#9a8a6a">No systems in library — generate one.</div>'; return; }
  let g = '';
  // zone bands + boundaries + labels
  for (const z of ZONES) {
    const [r0, r1] = ZONE_BAND[z];
    g += annulus(r0, r1, ZONE_TINT[z], 0.05);
    g += `<circle cx="${CX}" cy="${CY}" r="${r1}" fill="none" stroke="#4f3d27" stroke-width="1.6" stroke-opacity=".4" stroke-dasharray="8 5"/>`;
    g += `<text class="zone-label" x="${CX}" y="${CY - r1 + 26}" font-size="22">${ZONE_LABEL[z]}</text>`;
  }
  // orbits + elements
  let els = '';
  for (const z of ZONES) {
    const reals = realEls(z);
    reals.forEach((x, slot) => {
      const el = x.e, idx = x.i;
      const r = orbitR(z, slot, reals.length);
      const gl = elementGlyph(el);
      const p = elPos(z, idx);
      const isSel = sel && sel.kind === 'el' && sel.zone === z && sel.idx === idx;
      if (gl.belt) {
        g += `<circle cx="${CX}" cy="${CY}" r="${r}" fill="none" stroke="${INK}" stroke-opacity=".5" stroke-width="3" stroke-dasharray="1 7" pointer-events="none"/>`;
      } else {
        g += `<circle class="orbit" cx="${CX}" cy="${CY}" r="${r}"/>`;
      }
      const label = el.name ? `<text class="el-name" y="${gl.R + 30}">${esc(el.name)}</text>` : '';
      els += `<g class="element${isSel ? ' selected' : ''}" data-zone="${z}" data-idx="${idx}" transform="translate(${p.x.toFixed(1)},${p.y.toFixed(1)})">` +
        `<circle r="${gl.R + 14}" fill="transparent"/>` + gl.svg + `<circle class="halo" r="${gl.R + 10}"/>` + label + `</g>`;
    });
  }
  // star
  const starSel = sel && sel.kind === 'star';
  const star = `<g class="star-glyph${starSel ? ' selected' : ''}" transform="translate(${CX},${CY})">${starGlyph(S.star)}` +
    `<text class="el-name" y="156" style="font-size:24px">${esc(S.name)}</text></g>`;
  world.innerHTML = `<svg id="chart" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" xmlns="http://www.w3.org/2000/svg">` +
    `<rect width="${W}" height="${H}" fill="#e7dcc3" data-bg="1"/>` +
    `<circle cx="${CX}" cy="${CY}" r="962" fill="none" stroke="#4f3d27" stroke-width="3"/>` + g + els + star + `</svg>`;
  applyView();
  renderSidebar();
}
function applyView() {
  $('world').style.transform = `translate(${view.x}px,${view.y}px) scale(${view.k})`;
}

/* ---------- sidebar ---------- */
function renderSidebar() {
  // library select
  const ss = $('sys-select');
  ss.innerHTML = LIB.systems.map(s => `<option value="${esc(s.id)}"${S && s.id === S.id ? ' selected' : ''}>${esc(s.name)} (${esc(s.id)})</option>`).join('');
  $('lib-info').textContent = LIB.systems.length + ' system(s) in library';
  let n = 0; if (S) for (const z of ZONES) n += realEls(z).length;
  $('counts').textContent = S ? `${S.name}: ${n} elements` : '';
  $('dirty').textContent = dirty ? 'unsaved changes — Export to persist' : '';
  renderEditor();
}
function selBox(label, value, options, oninput, extra) {
  const opts = options.map(o => `<option${o === value ? ' selected' : ''}>${esc(o)}</option>`).join('');
  return `<label class="f">${label}</label><select data-act="${oninput}" ${extra || ''}>${value && !options.includes(value) ? `<option selected>${esc(value)}</option>` : ''}${opts}</select>`;
}
function renderEditor() {
  const ed = $('editor');
  if (!S) { ed.innerHTML = ''; return; }
  let h = '';
  if (sel && sel.kind === 'el') {
    const el = zoneElements(sel.zone)[sel.idx];
    if (!el) { sel = null; return renderEditor(); }
    const d = el.details || {};
    const isPlanet = el.element_type === 'Planet', isGas = el.element_type === 'Gas Giant';
    const reals = realEls(sel.zone);
    const slot = reals.findIndex(x => x.i === sel.idx);
    h += `<h2>Element</h2>
      <label class="f">Name</label><input type="text" data-act="el-name" value="${esc(el.name || '')}">
      ${selBox('Type', el.element_type, (OPT.element_types || []).filter(t => t !== 'No Feature'), 'el-type')}
      <div class="row2">
        <div>${selBox('Zone', sel.zone, ZONES, 'el-zone')}</div>
        <div><label class="f">Position</label><select data-act="el-slot">${reals.map((_, i) => `<option value="${i}"${i === slot ? ' selected' : ''}>${i + 1} of ${reals.length}</option>`).join('')}</select></div>
      </div>
      <label class="f">Bearing (°) — or drag on chart</label><input type="number" data-act="el-angle" value="${Math.round((el._ui && el._ui.angle) || 0)}">`;
    if (isPlanet || isGas) {
      const bodyOpts = isGas ? (OPT.body_gas || []) : (OPT.body_rocky || []);
      const gravOpts = isGas ? (OPT.gravity_gas || []) : (OPT.gravity || []);
      h += selBox('Body', d.body_size || d.body_class || '', bodyOpts, 'd-body')
        + selBox('Gravity', d.gravity || '', gravOpts, 'd-gravity')
        + selBox('Atmosphere', d.atmospheric_presence || '', OPT.atmospheric_presence || [], 'd-atm')
        + selBox('Composition', d.atmospheric_composition || '', OPT.atmospheric_composition || [], 'd-comp')
        + selBox('Climate', d.climate || '', OPT.climate || [], 'd-climate')
        + selBox('Habitability', d.habitability || '', OPT.habitability || [], 'd-hab');
      const feats = (d.orbital_features || []).map((f, i) => {
        const nm = typeof f === 'string' ? f : (f.name || '?');
        return `<div class="sr" style="display:flex;justify-content:space-between"><span>${esc(nm)}</span><span data-act="of-del" data-i="${i}" style="cursor:pointer;color:#e08080">✕</span></div>`;
      }).join('');
      h += `<label class="f">Orbital features</label><div class="pl-list">${feats || '<div class="hint">none</div>'}</div>
        <div class="row2"><select data-role="of-add-sel">${(OPT.orbital_features || []).map(o => `<option>${esc(o)}</option>`).join('')}</select>
        <button data-act="of-add">+ Add</button></div>`;
      if (d.inhabitants) h += `<label class="f">Inhabitants</label><div class="hint">${esc(typeof d.inhabitants === 'string' ? d.inhabitants : JSON.stringify(d.inhabitants))}</div>`;
    }
    h += `<div class="toolrow" style="margin-top:.6rem"><button class="danger" data-act="el-del">Remove Element</button></div>`;
  } else if (sel && sel.kind === 'star') {
    h += `<h2>Star</h2>${selBox('Type', (S.star && S.star.type) || '', OPT.star_types || [], 'star-type')}
      <div class="hint" style="margin-top:.4rem">${esc((S.star && S.star.description) || '')}</div>`;
  } else {
    const featNames = (S.system_features || []).map(f => typeof f === 'string' ? f : (f.name || f.feature || '')).filter(Boolean);
    h += `<h2>System</h2>
      <label class="f">Name</label><input type="text" data-act="sys-name" value="${esc(S.name)}">
      ${selBox('Star type', (S.star && S.star.type) || '', OPT.star_types || [], 'star-type')}
      <label class="f">System features</label>
      <div class="pl-list">${featNames.length ? featNames.map(f => `<div class="sr">${esc(f)}</div>`).join('') : '<div class="hint">none</div>'}</div>
      <label class="f">Add element</label>
      <div class="row2"><select data-role="add-zone">${ZONES.map(z => `<option value="${z}">${ZONE_LABEL[z].toLowerCase()}</option>`).join('')}</select>
      <select data-role="add-type">${(OPT.element_types || []).filter(t => t !== 'No Feature').map(t => `<option>${esc(t)}</option>`).join('')}</select></div>
      <div class="toolrow"><button data-act="el-add">+ Add Element</button>
      <button class="danger" data-act="sys-del">Delete System</button></div>
      <div class="hint" style="margin-top:.4rem">Click the star or any element on the chart to edit it. Drag an element to change its bearing.</div>`;
  }
  ed.innerHTML = h;
  wireEditor();
}

/* ---------- mutation helpers ---------- */
function pushUndo() {
  if (!S) return;
  (undoStacks[S.id] = undoStacks[S.id] || []).push(JSON.stringify(S));
  if (undoStacks[S.id].length > 60) undoStacks[S.id].shift();
  dirty = true;
}
function undo() {
  const st = S && undoStacks[S.id];
  if (!st || !st.length) return;
  const prev = JSON.parse(st.pop());
  const i = LIB.systems.findIndex(x => x.id === S.id);
  LIB.systems[i] = prev; S = prev;
  if (sel && sel.kind === 'el' && !zoneElements(sel.zone)[sel.idx]) sel = null;
  render();
}
function curEl() { return sel && sel.kind === 'el' ? zoneElements(sel.zone)[sel.idx] : null; }

function wireEditor() {
  const ed = $('editor');
  ed.querySelectorAll('[data-act]').forEach(node => {
    const act = node.dataset.act;
    const ev = node.tagName === 'BUTTON' || act === 'of-del' ? 'click' : 'change';
    node.addEventListener(ev, () => {
      const el = curEl();
      switch (act) {
        case 'sys-name': pushUndo(); S.name = node.value || S.name; break;
        case 'star-type': pushUndo(); S.star = S.star || {}; S.star.type = node.value; break;
        case 'sys-del': {
          if (!confirm('Delete system "' + S.name + '" from the library?')) return;
          pushUndo();
          LIB.systems = LIB.systems.filter(x => x.id !== S.id);
          S = LIB.systems[0] || null; sel = null; break;
        }
        case 'el-add': {
          pushUndo();
          const z = ed.querySelector('[data-role=add-zone]').value;
          const t = ed.querySelector('[data-role=add-type]').value;
          const el2 = { element_type: t, _ui: { angle: Math.floor(Math.random() * 360) }, _source: 'user-added via system_tool' };
          if (t === 'Planet' || t === 'Gas Giant') el2.details = { orbital_features: [] };
          zoneElements(z).push(el2);
          ensureDefaults(S);
          sel = { kind: 'el', zone: z, idx: zoneElements(z).length - 1 };
          break;
        }
        case 'el-name': pushUndo(); el.name = node.value; break;
        case 'el-type': {
          pushUndo(); el.element_type = node.value;
          if (node.value === 'Planet' || node.value === 'Gas Giant') { el.details = el.details || { orbital_features: [] }; }
          else delete el.details;
          ensureDefaults(S);
          break;
        }
        case 'el-zone': {
          pushUndo();
          const z2 = node.value;
          const [moved] = zoneElements(sel.zone).splice(sel.idx, 1);
          zoneElements(z2).push(moved);
          sel = { kind: 'el', zone: z2, idx: zoneElements(z2).length - 1 };
          break;
        }
        case 'el-slot': {
          pushUndo();
          const reals = realEls(sel.zone);
          const target = reals[+node.value].i;
          const arr = zoneElements(sel.zone);
          const [moved] = arr.splice(sel.idx, 1);
          arr.splice(target, 0, moved);
          sel = { kind: 'el', zone: sel.zone, idx: target };
          break;
        }
        case 'el-angle': pushUndo(); el._ui = el._ui || {}; el._ui.angle = ((+node.value % 360) + 360) % 360; break;
        case 'el-del': {
          pushUndo(); zoneElements(sel.zone).splice(sel.idx, 1); sel = null; break;
        }
        case 'd-body': pushUndo(); el.details = el.details || {}; if ('body_class' in el.details && el.element_type === 'Gas Giant') el.details.body_class = node.value; else el.details.body_size = node.value; break;
        case 'd-gravity': pushUndo(); el.details.gravity = node.value; break;
        case 'd-atm': pushUndo(); el.details.atmospheric_presence = node.value; break;
        case 'd-comp': pushUndo(); el.details.atmospheric_composition = node.value; break;
        case 'd-climate': pushUndo(); el.details.climate = node.value; break;
        case 'd-hab': pushUndo(); el.details.habitability = node.value; break;
        case 'of-add': {
          pushUndo(); el.details.orbital_features = el.details.orbital_features || [];
          el.details.orbital_features.push(ed.querySelector('[data-role=of-add-sel]').value);
          break;
        }
        case 'of-del': pushUndo(); el.details.orbital_features.splice(+node.dataset.i, 1); break;
        default: return;
      }
      render();
    });
  });
}

/* ---------- chart interaction ---------- */
function svgPoint(e) {
  const vp = $('viewport').getBoundingClientRect();
  return { x: (e.clientX - vp.left - view.x) / view.k, y: (e.clientY - vp.top - view.y) / view.k };
}
function wireViewport() {
  const vp = $('viewport');
  vp.addEventListener('mousedown', e => {
    const elG = e.target.closest && e.target.closest('.element');
    const starG = e.target.closest && e.target.closest('.star-glyph');
    if (elG) {
      sel = { kind: 'el', zone: elG.dataset.zone, idx: +elG.dataset.idx };
      drag = { kind: 'el', moved: false, undone: false };
      render();
    } else if (starG) {
      sel = { kind: 'star' }; render();
    } else {
      if (sel && e.target.dataset && e.target.dataset.bg) { sel = null; render(); }
      drag = { kind: 'pan', sx: e.clientX, sy: e.clientY, ox: view.x, oy: view.y };
      vp.classList.add('panning');
    }
    e.preventDefault();
  });
  window.addEventListener('mousemove', e => {
    if (!drag) { hover(e); return; }
    if (drag.kind === 'pan') {
      view.x = drag.ox + e.clientX - drag.sx; view.y = drag.oy + e.clientY - drag.sy;
      applyView();
    } else if (drag.kind === 'el' && sel && sel.kind === 'el') {
      if (!drag.undone) { pushUndo(); drag.undone = true; }
      drag.moved = true;
      const p = svgPoint(e);
      const a = Math.atan2(p.y - CY, p.x - CX) * 180 / Math.PI;
      const el = curEl();
      el._ui = el._ui || {}; el._ui.angle = ((a % 360) + 360) % 360;
      render();
    }
  });
  window.addEventListener('mouseup', () => { drag = null; vp.classList.remove('panning'); });
  vp.addEventListener('wheel', e => {
    e.preventDefault();
    const f = e.deltaY < 0 ? 1.12 : 1 / 1.12;
    const r = vp.getBoundingClientRect(), mx = e.clientX - r.left, my = e.clientY - r.top;
    view.x = mx - (mx - view.x) * f; view.y = my - (my - view.y) * f;
    view.k = Math.min(4, Math.max(0.12, view.k * f));
    applyView();
  }, { passive: false });
}
function hover(e) {
  const hc = $('hovercard');
  const elG = e.target.closest && e.target.closest('.element');
  const starG = e.target.closest && e.target.closest('.star-glyph');
  let html = '';
  if (elG && S) {
    const el = zoneElements(elG.dataset.zone)[+elG.dataset.idx];
    if (el) {
      const d = el.details || {};
      html = `<div class="hc-title">${esc(el.name || el.element_type)}</div>` +
        `<div>${esc(el.element_type)} — ${esc(ZONE_LABEL[elG.dataset.zone].toLowerCase())}</div>`;
      if (d.body_size || d.body_class) html += `<div>Body: ${esc(d.body_size || d.body_class)}${d.gravity ? ' · ' + esc(d.gravity) : ''}</div>`;
      if (d.climate) html += `<div>${esc(d.climate)} · ${esc(d.habitability || '')}</div>`;
      if (d.atmospheric_presence) html += `<div>Atmosphere: ${esc(d.atmospheric_presence)}${d.atmospheric_composition ? ' (' + esc(d.atmospheric_composition) + ')' : ''}</div>`;
      const nf = (d.orbital_features || []).length;
      if (nf) html += `<div>${nf} orbital feature(s)</div>`;
    }
  } else if (starG && S) {
    html = `<div class="hc-title">${esc(S.name)}</div><div>${esc((S.star && S.star.type) || '')} star</div>` +
      `<div style="max-width:260px">${esc((S.star && S.star.description) || '')}</div>`;
  }
  if (html) {
    hc.innerHTML = html; hc.style.display = 'block';
    const vp = $('viewport').getBoundingClientRect();
    hc.style.left = Math.min(e.clientX - vp.left + 16, vp.width - 310) + 'px';
    hc.style.top = (e.clientY - vp.top + 14) + 'px';
  } else hc.style.display = 'none';
}

/* ---------- library / io ---------- */
function selectSystem(id, pushHash) {
  S = LIB.systems.find(x => x.id === id) || LIB.systems[0] || null;
  sel = null;
  if (S) { ensureDefaults(S); if (pushHash !== false) location.hash = S.id; }
  fitView();
  render();
}
function fitView() {
  const vp = $('viewport').getBoundingClientRect();
  const k = Math.max(0.12, Math.min(vp.width, vp.height) / 2050);
  view = { k, x: (vp.width - W * k) / 2, y: (vp.height - H * k) / 2 };
}
function download(name, text) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([text], { type: 'application/json' }));
  a.download = name; a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 5000);
}
function wireChrome() {
  $('sys-select').addEventListener('change', e => selectSystem(e.target.value));
  $('b-undo').addEventListener('click', undo);
  window.addEventListener('keydown', e => {
    if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 'z') { e.preventDefault(); undo(); }
  });
  $('b-export').addEventListener('click', () => { download('library.json', JSON.stringify(LIB, null, 1)); dirty = false; renderSidebar(); });
  $('b-import').addEventListener('click', () => $('file-import').click());
  $('file-import').addEventListener('change', e => {
    const f = e.target.files[0]; if (!f) return;
    const rd = new FileReader();
    rd.onload = () => {
      try {
        const j = JSON.parse(rd.result);
        if (!Array.isArray(j.systems)) throw new Error('no systems[]');
        LIB.systems = j.systems; dirty = true;
        selectSystem(LIB.systems[0] && LIB.systems[0].id);
      } catch (err) { alert('Import failed: ' + err.message); }
    };
    rd.readAsText(f);
  });
  // generate command builder
  const updCmd = () => {
    const seed = $('gen-seed').value, name = $('gen-name').value.trim();
    let c = 'python gen_system.py';
    if (seed) c += ' --seed ' + seed;
    if (name) c += ' --name "' + name.replace(/"/g, '') + '"';
    $('gen-cmd').textContent = c;
  };
  $('gen-seed').addEventListener('input', updCmd);
  $('gen-name').addEventListener('input', updCmd);
  $('b-copycmd').addEventListener('click', () => {
    const txt = $('gen-cmd').textContent;
    if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(txt);
    else {
      const ta = document.createElement('textarea');
      ta.value = txt; document.body.appendChild(ta); ta.select();
      document.execCommand('copy'); ta.remove();
    }
    $('b-copycmd').textContent = 'Copied ✓';
    setTimeout(() => { $('b-copycmd').textContent = 'Copy command'; }, 1200);
  });
  // collapsible sections
  document.querySelectorAll('.sec>h2').forEach(h2 =>
    h2.addEventListener('click', () => h2.parentElement.classList.toggle('collapsed')));
  window.addEventListener('hashchange', () => {
    const id = location.hash.slice(1);
    if (id && S && id !== S.id) selectSystem(id, false);
  });
  window.addEventListener('resize', () => { fitView(); applyView(); });
}

